DLDIRECT_IMAGE_END
RX_BUF_SIZE	EQU 1518

	MODULE MAIN

OUR_IP		EQU APP_BSS_BASE
OUR_MAC		EQU APP_BSS_BASE + 4
TARGET_IP	EQU APP_BSS_BASE + 10
TARGET_MAC	EQU APP_BSS_BASE + 14
TIMEOUT_MS_LEFT EQU APP_BSS_BASE + 20
PORT_WORD	EQU APP_BSS_BASE + 22
CANCELLED	EQU APP_BSS_BASE + 24
TCP_IS_OPEN	EQU APP_BSS_BASE + 25
CMDLINE_PTR	EQU APP_BSS_BASE + 26
HELP_REQUESTED	EQU APP_BSS_BASE + 28
API_STATUS	EQU APP_BSS_BASE + 29
ALIGN_SECOND	EQU APP_BSS_BASE + 30
ALIGN_LEFT	EQU APP_BSS_BASE + 33
STOP_TIME	EQU APP_BSS_BASE + 35
STOP_ELAPSED	EQU APP_BSS_BASE + 38

URL_BUFF	EQU DHTTP_BSS_BASE + DHTTP_BSS_SIZE
HOST_BUFF	EQU URL_BUFF + URL_SIZE
PORT_BUFF	EQU HOST_BUFF + HOST_SIZE
PATH_BUFF	EQU PORT_BUFF + PORT_SIZE
REQ_BUFF	EQU PATH_BUFF + PATH_SIZE
HEADER_BUFF	EQU REQ_BUFF + REQ_SIZE
	IFDEF DLDIRECT_COPY
DIRECT_COPY_BUF EQU HEADER_BUFF + HEADER_SIZE
APP_BSS_END	EQU DIRECT_COPY_BUF + 536
	ELSE
APP_BSS_END	EQU HEADER_BUFF + HEADER_SIZE
	ENDIF

TX_BUF		EQU DLDIRECT_IMAGE_END
RX_HDR		EQU TX_BUF + TCP_MAX_FRAME
RX_BUF		EQU RX_HDR + 4

	ASSERT RX_BUF + RX_BUF_SIZE < 0x8000
	ASSERT APP_BSS_END < RT_STACK_TOP - 0x0100
	ENDMODULE

	END MAIN.START

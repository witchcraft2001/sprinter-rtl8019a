	CALL	APPEND_STR
	LD	DE,PORT_BUFF
	CALL	APPEND_STR
.DEFAULT
	LD	DE,REQ_END
	JP	APPEND_STR
APPEND_STR
	LD	A,(DE)
	LD	(HL),A
	OR	A
	RET	Z
	INC	HL
	INC	DE
	JR	APPEND_STR
COPY_ASCIIZ
	LD	A,(HL)
	LD	(DE),A
	OR	A
	RET	Z
	INC	HL
	INC	DE
	JR	COPY_ASCIIZ
STARTSWITH
	PUSH	HL
.LOOP
	LD	A,(DE)
	OR	A
	JR	Z,.MATCH
	CP	(HL)
	JR	NZ,.MISS
	INC	HL
	INC	DE
	JR	.LOOP
.MATCH
	POP	HL
	XOR	A
	RET
.MISS
	POP	HL
	LD	A,0xFF
	OR	A
	RET
STREQ
	LD	A,(DE)
	LD	C,A
	LD	A,(HL)
	CP	C
	RET	NZ
	AND	A
	RET	Z
	INC	HL
	INC	DE
	JR	STREQ
STRLEN
	LD	BC,0
.LOOP
	LD	A,(HL)
	OR	A
	RET	Z
	INC	HL
	INC	BC
	JR	.LOOP

PUT_CHAR
	PUSH	AF,BC,DE,HL
	LD	C,DSS_PUTCHAR
	RST	DSS
	POP	HL,DE,BC,AF
	RET
CRLF

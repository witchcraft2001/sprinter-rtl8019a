; UNETRTL stop-and-wait sender. Included inside MODULE TCP, DLL only.
; SEND_SEQ/ACK_WAIT_TARGET describe the ORIGINAL caller chunk throughout
; AGAIN; FLIGHT_END describes only the segment currently awaiting its ACK.
; All persistent state is in the channel's swapped BSS. The caller retains
; its source buffer; wire retries always start at the confirmed prefix.
SEND
	LD	(.CALL_LEN),BC
	LD	(.CALL_DATA),HL
	LD	HL,TCP_SND_UNA
	LD	DE,TCP_SEND_SEQ
	CALL	COPY_SEQ32
	LD	HL,TCP_SEND_SEQ
	LD	DE,TCP_ACK_WAIT_TARGET
	CALL	COPY_SEQ32
	LD	BC,(.CALL_LEN)
	LD	DE,TCP_ACK_WAIT_TARGET
	CALL	ADD32_BE_BC
	XOR	A
	LD	(TCP_PERSIST),A
	CALL	.NEW_ATTEMPT
	JP	.TRANSMIT
.NEW_ATTEMPT
	LD	A,SEND_ATTEMPTS
	LD	(TCP_SEND_RETRY_LEFT),A
	LD	HL,SEND_ACK_TIMEOUT_MS
	LD	(TCP_PERSIST_INTERVAL),HL
	LD	(TCP_ATTEMPT_MS_LEFT),HL
	RET
.SLICE
	LD	A,1
	LD	(.WORK_LEFT+1),A
	RET
; One wire send OR one bounded receive step per asynchronous public call.
; Save the CALL address, so resume consumes its own fresh work quantum.
.STEP
	LD	HL,(@UNET.OPT_SLICE)
	LD	A,H
	OR	L
	RET	Z
.WORK_LEFT
	LD	A,1
	DEC	A
	LD	(.WORK_LEFT+1),A
	RET	Z
	POP	HL
	DEC	HL
	DEC	HL
	DEC	HL
	LD	(.NEXT+1),HL
	JP	.AGAIN
.TRANSMIT
	CALL	.STEP
	CALL	ACK_TARGET_MATCH
	JP	Z,.OK
	LD	HL,(TCP_PEER_WIN)
	LD	A,H
	OR	L
	JP	Z,.ZERO_WINDOW
	XOR	A
	LD	(TCP_PERSIST),A
	; The remainder is <= MSS. Restrict every burst to the peer window.
	CALL	.PROGRESS
	LD	(.BEFORE),HL
	EX DE,HL
	LD	HL,(.CALL_LEN)
	OR	A
	SBC	HL,DE
	LD	BC,(TCP_PEER_WIN)
	PUSH	HL
	OR	A
	SBC	HL,BC
	POP	HL
	JR	C,.LENGTH_READY
	LD	H,B
	LD	L,C
.LENGTH_READY
	LD	(.SAVE_LEN),HL
	JP	.WIRE
.ZERO_WINDOW
	LD	A,(TCP_PERSIST)
	OR	A
	JP	NZ,.WAIT
	INC	A
	LD	(TCP_PERSIST),A
	LD	(TCP_PROBE_LIVE),A
	CALL	.NEW_ATTEMPT
	JP	.WAIT
.PROBE
	CALL	.STEP
	; One octet at SND.UNA elicits the lost window update. It may be
	; accepted when the window opens; normal cumulative ACK accounts for it.
	CALL	.PROGRESS
	LD	(.BEFORE),HL
	LD	HL,1
	LD	(.SAVE_LEN),HL
.WIRE
	LD	HL,(.CALL_DATA)
	LD	DE,(.BEFORE)
	ADD	HL,DE
	LD	(.SAVE_DATA),HL
	CALL	BUILD_DATA
	LD	HL,TCP_SND_UNA
	LD	DE,TCP_FLIGHT_END
	CALL	COPY_SEQ32
	LD	BC,(.SAVE_LEN)
	LD	DE,TCP_FLIGHT_END
	CALL	ADD32_BE_BC
	LD	HL,TCP_FLIGHT_END+3
	LD	DE,TCP_SND_NXT+3
	CALL	UPDATE_SEND_ACK.ACK_DIFF
	JP	M,.KEEP_HIGH
	LD	HL,TCP_FLIGHT_END
	LD	DE,TCP_SND_NXT
	CALL	COPY_SEQ32
.KEEP_HIGH
	XOR	A
	LD	(TCP_PROBE_LIVE),A
	LD	HL,(.SAVE_DATA)
	LD	(@RTL.TX_PAY_PTR),HL
	LD	HL,(.SAVE_LEN)
	LD	(@RTL.TX_PAY_LEN),HL
	LD	HL,@MAIN.TX_BUF
	LD	BC,54
	CALL	@RTL.SEND_FRAME_SG
	JP	C,FAIL_SEND
.WAIT
	CALL	.STEP
	LD	A,ACK_WAIT_ACTIVE
	LD	(TCP_ACK_WAIT_STATE),A
	LD	HL,(@UNET.OPT_SLICE)
	LD	A,H
	OR	L
	JR	Z,.BLOCK_WAIT
	; One paced tick plus one ring poll. No loop over foreign traffic.
	CALL	@MAIN.TICK_AND_CHECK_KEY
	JP	C,RECV.CANCEL
	LD	HL,1
	JR	.QUANTUM_READY
.BLOCK_WAIT
	LD	HL,(TCP_ATTEMPT_MS_LEFT)
.QUANTUM_READY
	LD	(.QUANTUM),HL
	LD	(RECV_TIMEOUT),HL
	CALL	RECV
	PUSH	AF
	; Charge protocol time independently of the public work quantum.
	; RECV exposes its unused poll budget. Charge at least one tick
	; so immediate events cannot freeze the retry/persist budget.
	LD	HL,(.QUANTUM)
	LD	DE,(TCP_TIMEOUT_LEFT)
	OR	A
	SBC	HL,DE
	LD	A,H
	OR	L
	JR	NZ,.ELAPSED
	INC	HL
.ELAPSED
	EX DE,HL
	LD	HL,(TCP_ATTEMPT_MS_LEFT)
	OR	A
	SBC	HL,DE
	LD	(TCP_ATTEMPT_MS_LEFT),HL
	POP	AF
	JR	NC,.EVENT
	CALL	ACK_TARGET_MATCH
	JP	Z,.OK
	LD	A,(TCP_LAST_FAIL)
	CP	F_OTHER
	JR	NZ,.WAIT_ERROR
	LD	HL,(@UNET.OPT_SLICE)
	LD	A,H
	OR	L
	JP	NZ,.WAIT		; yield with the receive continuation parked
	CALL	@UNET.DROP_FOREIGN_UDP	; blocking calls never return AGAIN
	JR	.EVENT
.WAIT_ERROR
	CP	F_TIMEOUT
	SCF
	RET	NZ                         ; FIN/RST/cancel/NIC remain distinct
.EVENT
	CALL	ACK_TARGET_MATCH
	JP	Z,.OK
	LD	HL,(TCP_ATTEMPT_MS_LEFT)
	LD	A,H
	OR	L
	JR	Z,.EXPIRED
	LD	HL,(TCP_PEER_WIN)
	LD	A,H
	OR	L
	JR	Z,.STILL_ZERO
	LD	A,(TCP_PERSIST)
	OR	A
	JP	NZ,.RESTART
	CALL	.PROGRESS
	LD	DE,(.BEFORE)
	OR	A
	SBC	HL,DE
	JP	Z,.WAIT
.RESTART
	CALL	.NEW_ATTEMPT
	JP	.TRANSMIT
.STILL_ZERO
	LD	A,(TCP_PERSIST)
	OR	A
	JP	Z,.ZERO_WINDOW
	JP	.WAIT
.EXPIRED
	LD	A,(TCP_PERSIST)
	OR	A
	JR	Z,.RETRY
	LD	A,(TCP_PROBE_LIVE)
	OR	A
	JR	Z,.RETRY
	LD	A,SEND_ATTEMPTS+1           ; living peer never burns data retries
	LD	(TCP_SEND_RETRY_LEFT),A
.RETRY
	LD	HL,TCP_SEND_RETRY_LEFT
	DEC	(HL)
	JR	Z,.TIMEOUT
	LD	HL,(TCP_PERSIST_INTERVAL)
	LD	A,(TCP_PERSIST)
	OR	A
	JR	Z,.REARM
	LD	DE,4000
	OR	A
	SBC	HL,DE
	ADD	HL,DE
	JR	NC,.REARM
	ADD	HL,HL
.REARM
	LD	(TCP_PERSIST_INTERVAL),HL
	LD	(TCP_ATTEMPT_MS_LEFT),HL
	LD	A,(TCP_PERSIST)
	OR	A
	JP	NZ,.PROBE
	JP	.TRANSMIT
.AGAIN
	LD	A,F_AGAIN
	JP	FAIL_A
.TIMEOUT
	LD	A,F_TIMEOUT
	JP	FAIL_A
.OK
	XOR	A
	LD	(TCP_ACK_WAIT_STATE),A
	LD	(TCP_LAST_FAIL),A
	RET
.RESTORE_SEQ
	LD	HL,TCP_SND_UNA
	LD	DE,TCP_SND_NXT
	JP	COPY_SEQ32
.PROGRESS
	LD	A,(TCP_SND_UNA+3)
	LD	L,A
	LD	A,(TCP_SND_UNA+2)
	LD	H,A
	LD	A,(TCP_SEND_SEQ+3)
	LD	E,A
	LD	A,(TCP_SEND_SEQ+2)
	LD	D,A
	OR	A
	SBC	HL,DE
	RET
.CALL_LEN	DW	0
.CALL_DATA	DW	0
.SAVE_LEN	DW	0
.SAVE_DATA	DW	0
.BEFORE	DW	0
.QUANTUM	DW	0
; Only one public TCP SEND may be pending, independent of channel swaps.
.NEXT	LD	HL,0
	JP	(HL)
SEND_RESUME
	LD	(SEND.CALL_LEN),BC
	LD	(SEND.CALL_DATA),HL
	CALL	SEND.SLICE
	JP	SEND.NEXT
